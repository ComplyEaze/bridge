// Owner rule of 25 Oct 2026: no AI attribution in public text. The merge gate (scripts/merge-gate.sh) feeds this the
// pull request's title, body and commits as one JSON object on stdin and refuses when
//   - the title or the body, comments included, holds a "Generated with Claude" line (plain, Markdown-link, "by" and
//     "using" forms; Claude or Anthropic) or a Co-authored-by trailer naming an assistant (Claude, Anthropic, Fable, Copilot,
//     Codex, OpenAI, ChatGPT), or
//   - a commit carries such a trailer or line, or has an author or committer identity that names an assistant, and is not
//     one of the accepted older commits.
// The accepted older commits are pinned by SHA in scripts/check-ai-attribution-accepted.json (the owner's decision of 26 Oct
// 2026: accept the commits of the branches that were open then, block every new one). A commit is accepted by its SHA and not
// by its date, because a committer date is the pusher's to set; an accepted commit with such text is reported as a NOTE, and a
// note says that GitHub's squash merge can copy it into the commit on master as a Co-authored-by line. Any other commit with
// such text is refused, however old it claims to be; a rebased accepted branch has new SHAs and needs the list updated, which
// is a change to the gate and so the owner's act.
// Text is read after normalisation, so that ordinary Markdown, HTML entities, invisible characters and look-alike letters
// do not hide a line: NFKC, format characters removed, entities decoded, Unicode dashes made "-", a few Cyrillic and
// Greek look-alikes made Latin, and (for the "Generated" line) Markdown and HTML punctuation read as spaces.
// Limits: prose that quotes the banned line ("fixtures generated by Claude Code") is refused like the line itself; only a short table of
// Cyrillic and Greek look-alike letters is read (a full confusables table is not), and a deliberate paraphrase is not caught.
//
// Input:  {"title": string, "body": string, "accepted": [sha] (optional),
//          "commits": [{"sha": string, "message": string, "identities": [string] (optional)}]}
// Output: one line per finding, "REFUSE <where>: <what>" or "NOTE <where>: <what>", then "CHECKED <n>"; exit 0 clean, 1 refused, 2 bad input.
// Run:    node scripts/check-ai-attribution.mjs < input.json

import { realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

// The assistants the rule names: Claude and Anthropic's model family names, and the other assistants that sign commits.
// Names are matched wherever they sit ("ClaudeBot", "GitHubCopilot"), except that "Claudette" is a person.
const AGENT = "(?:claude(?!tte)|anthropic|fable|copilot|codex|openai|chatgpt)";
// The generated-with line is the one the assistant adds; a sentence about another vendor's model ("generated with OpenAI") is ordinary text.
const GENERATED_LINE = /generated\W+(?:with|by|using)\W+(?:an?\W+)?(?:claude(?!tte)|anthropic)/i;
const CO_AUTHOR_TRAILER = new RegExp(`^[ \\t]*co-authored-by[ \\t]*:[^\\r\\n]*${AGENT}[^\\r\\n]*$`, "im");
const IDENTITY = new RegExp(AGENT, "i");

const NAMED_ENTITIES = { nbsp: " ", amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", ensp: " ", emsp: " ", thinsp: " " };
// Letters of the words above that Cyrillic and Greek write with the same shape as a Latin one.
const LOOKALIKES = { "а": "a", "с": "c", "е": "e", "о": "o", "р": "p", "і": "i", "ѕ": "s", "ԁ": "d",
  "А": "A", "С": "C", "Е": "E", "О": "O", "Р": "P", "І": "I", "Ѕ": "S", "ο": "o", "ι": "i", "Ο": "O", "Ι": "I",
  "\u03b1": "a", "\u03c5": "u", "\u03f2": "c", "\u03c2": "c", "\u1d04": "c", "\u04c0": "I" };

function decodeEntities(text) {
  return text.replace(/&(?:#x([0-9a-f]{1,6})|#(\d{1,7})|([a-z]{2,8}));/gi, (whole, hex, dec, name) => {
    if (name !== undefined) return NAMED_ENTITIES[name.toLowerCase()] ?? whole;
    const code = hex !== undefined ? Number.parseInt(hex, 16) : Number.parseInt(dec, 10);
    return code >= 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
  });
}

export function normalise(text) {
  // Format characters and combining marks (a joiner, a variation selector, an accent) are invisible or decorative: drop them.
  const plain = (value) => value.normalize("NFKD").replace(/[\p{Cf}\p{M}]/gu, "").normalize("NFKC");
  let t = plain(text);
  t = plain(decodeEntities(t));
  t = t.replace(/\p{Pd}/gu, "-").replace(/[\u0370-\u03ff\u0400-\u052f\u1d00-\u1d7f]/g, (c) => LOOKALIKES[c] ?? c);
  return t;
}

// The signature line is read two ways: with Markdown and HTML punctuation as spaces ("Generated with: **Claude Code**"), and with
// markup removed so it cannot split a word ("Gen<!-- x -->erated", "Cl*au*de", "Generated with <b>Claude</b> Code").
const generatedLine = (text) => {
  const t = normalise(text);
  const spaced = t.replace(/[<>*_`~|:()[\]]/g, " ");
  const joined = t.replace(/<!--[\s\S]*?-->/g, "").replace(/<\/?[a-z][^>]*>/gi, "").replace(/\]\([^)]*\)/g, "").replace(/[*_~`\\]/g, "");
  return GENERATED_LINE.test(spaced) || GENERATED_LINE.test(joined.replace(/[<>|:()[\]]/g, " "));
};
const coAuthorTrailer = (text) => CO_AUTHOR_TRAILER.test(normalise(text));

// What a commit carries that the rule names: a list of short descriptions, empty for a clean commit.
export function commitFindings(commit) {
  const found = [];
  if (coAuthorTrailer(commit.message)) found.push("a Co-authored-by trailer naming an assistant");
  if (generatedLine(commit.message)) found.push('a "Generated with" line naming an assistant');
  if ((commit.identities ?? []).some((identity) => IDENTITY.test(normalise(identity)))) found.push("an author or committer identity naming an assistant");
  return found;
}

export function evaluate(input) {
  const accepted = new Set((input.accepted ?? []).map((sha) => sha.toLowerCase()));
  const refusals = [];
  const notes = [];
  for (const [where, text] of [["title", input.title], ["body", input.body]]) {
    if (generatedLine(text)) refusals.push(`${where}: a "Generated with" line naming an assistant`);
    if (coAuthorTrailer(text)) refusals.push(`${where}: a Co-authored-by line naming an assistant (a squash merge copies the body into the commit on master)`);
  }
  for (const commit of input.commits) {
    const found = commitFindings(commit);
    if (found.length === 0) continue;
    const label = `commit ${commit.sha.slice(0, 12)}`;
    if (accepted.has(commit.sha.toLowerCase())) notes.push(`${label}: ${found.join(" and ")}; accepted older commit, but a squash merge can copy it into the commit on master as a Co-authored-by line`);
    else refusals.push(`${label}: ${found.join(" and ")}, and it is not one of the accepted older commits`);
  }
  return { refusals, notes };
}

function parseInput(text) {
  let input;
  try {
    input = JSON.parse(text);
  } catch {
    return null;
  }
  const isString = (value) => typeof value === "string";
  const isStrings = (value) => value === undefined || (Array.isArray(value) && value.every(isString));
  if (input === null || typeof input !== "object" || !isString(input.title) || !isString(input.body) || !Array.isArray(input.commits)) return null;
  if (!isStrings(input.accepted)) return null;
  if (!input.commits.every((c) => c !== null && typeof c === "object" && isString(c.sha) && isString(c.message) && isStrings(c.identities))) return null;
  return input;
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const input = parseInput(Buffer.concat(chunks).toString("utf8"));
  if (input === null) {
    console.error("check-ai-attribution: the input is not the expected JSON object");
    process.exit(2);
  }
  const { refusals, notes } = evaluate(input);
  for (const line of refusals) console.log(`REFUSE ${line}`);
  for (const line of notes) console.log(`NOTE ${line}`);
  // The last line says the check ran to the end; the gate trusts no answer without it.
  console.log(`CHECKED ${input.commits.length}`);
  process.exit(refusals.length > 0 ? 1 : 0);
}
