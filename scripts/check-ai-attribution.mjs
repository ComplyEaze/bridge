// Owner rule of 25 Oct 2026, kept as a practice and not a mandate: AI attribution does not belong in public text. The merge gate
// (scripts/merge-gate.sh) feeds this the pull request's title, body and commits as one JSON object on stdin and reports, as notes
// that never block a merge, where it finds
//   - a "Generated with Claude" line in the title or the body, comments included (plain, Markdown-link, "by" and "using" forms;
//     Claude or Anthropic), or a Co-authored-by trailer naming an assistant (Claude, Anthropic, Fable, Copilot, Codex, OpenAI,
//     ChatGPT, Gemini, Aider, Cursor Agent, Devin AI, Amazon Q, Jules Bot), or
//   - a commit that carries such a trailer or line, or has an author or committer identity that names an assistant.
// A note says that GitHub's squash merge copies the body, and a trailer, into the commit on master as a Co-authored-by line.
// Text is read after normalisation, so that ordinary Markdown, HTML entities, invisible characters and look-alike letters
// do not hide a line: NFKC, format characters removed, entities decoded, Unicode dashes made "-", a few Cyrillic and
// Greek look-alikes made Latin, and (for the "Generated" line) Markdown and HTML punctuation read as spaces.
// Limits: prose that quotes the line ("fixtures generated by Claude Code") is noted like the line itself; only a short table of
// Cyrillic and Greek look-alike letters is read (a full confusables table is not), and a deliberate paraphrase is not caught.
//
// Input:  {"title": string, "body": string,
//          "commits": [{"sha": string, "message": string, "identities": [string] (optional)}]}
// Output: one line per finding, "NOTE <where>: <what>", then "CHECKED <n>"; exit 0 whatever it found, 2 on bad input.
// Run:    node scripts/check-ai-attribution.mjs < input.json

import { existsSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

// The assistants the rule names: Claude and Anthropic's model family names, and the other assistants that sign commits.
// Names are matched wherever they sit ("ClaudeBot", "GitHubCopilot"), except that "Claudette" is a person.
// "fable", "anthropic", "codex", "gemini" and "aider" must not sit inside a longer word ("affable", "philanthropic", "raider"). The
// other assistants are matched by the name they sign with ("Cursor Agent", "Devin AI", "Amazon Q", "Jules Bot"), because their bare
// first words are ordinary names.
const AGENT = "(?:claude(?!tte)|(?<![a-z])anthropic|(?<![a-z])fable(?![a-z])|copilot|(?<![a-z])codex(?![a-z])|openai|chatgpt|(?<![a-z])(?:opus|sonnet|haiku)(?![a-z])|(?<![a-z])gemini(?![a-z])|(?<![a-z])aider(?![a-z])|cursor\\W{0,3}agent|(?<![a-z])devin\\W{0,3}ai(?![a-z])|amazon\\W{0,3}q(?![a-z])|jules\\W{0,3}bot|google-labs-jules)";
// The generated-with line is the one the assistant adds; a sentence about another vendor's model ("generated with OpenAI") is ordinary text.
const GENERATED_LINE = /generated\W+(?:with|by|using)\W+(?:(?:an?|the)\W+)?(?:claude(?!tte)|anthropic)/i;
const CO_AUTHOR_TRAILER = new RegExp(`^[ \\t>#+*_~\`-]*co-authored-by[ \\t]*:[^\\r\\n]*${AGENT}[^\\r\\n]*$`, "im");
const IDENTITY = new RegExp(AGENT, "i");

const NAMED_ENTITIES = { nbsp: " ", amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", ensp: " ", emsp: " ", thinsp: " " };
// Letters of the words above that Cyrillic and Greek write with the same shape as a Latin one.
const LOOKALIKES = { "а": "a", "с": "c", "е": "e", "о": "o", "р": "p", "і": "i", "ѕ": "s", "ԁ": "d",
  "А": "A", "С": "C", "Е": "E", "О": "O", "Р": "P", "І": "I", "Ѕ": "S", "ο": "o", "ι": "i", "Ο": "O", "Ι": "I",
  "\u03b1": "a", "\u03c5": "u", "\u03f2": "c", "\u03c2": "c", "\u1d04": "c", "\u04c0": "I" };

function decodeEntities(text) {
  return text.replace(/&(?:#x([0-9a-f]{1,6})|#(\d{1,7})|([a-z]{2,8}));/gi, (whole, hex, dec, name) => {
    if (name !== undefined) return NAMED_ENTITIES[name.toLowerCase()] ?? whole;
    const code = hex !== undefined ? Number.parseInt(hex, 16) : Number.parseInt(dec, 10);
    return code >= 0 && code <= 0x10ffff ? String.fromCodePoint(code) : whole;
  });
}

export function normalise(text) {
  // Format characters and combining marks (a joiner, a variation selector, an accent) are invisible or decorative: drop them.
  const plain = (value) => value.normalize("NFKD").replace(/[\p{Cf}\p{M}\p{Default_Ignorable_Code_Point}]/gu, "").normalize("NFKC");
  let t = plain(text);
  t = plain(decodeEntities(t));
  t = t.replace(/\p{Pd}/gu, "-").replace(/[\u0370-\u03ff\u0400-\u052f\u1d00-\u1d7f]/g, (c) => LOOKALIKES[c] ?? c);
  return t;
}

// The signature line is read three ways, so that Markdown and HTML cannot split it or hide a word break: (1) with Markdown and HTML
// punctuation as spaces ("Generated with: **Claude Code**"); (2) with markup and entities deleted ("Gen<!-- x -->erated", "Cl*au*de",
// "Cl&zwj;aude"); (3) with tags and entities as spaces ("Generated with<br>Claude Code"). A tag is read with quoted attributes ("a>b").
const TAG = /<\/?[a-z](?:"[^"]*"|'[^']*'|[^"'<>])*>/gi;
const COMMENT = /<!--[\s\S]*?-->/g;
const ENTITY = /&[a-z][a-z0-9]*;/gi;
const generatedLine = (text) => {
  const t = normalise(text);
  const spaced = t.replace(ENTITY, " ").replace(/[<>*_`~|:()[\]]/g, " ");
  const unmarked = t.replace(COMMENT, "").replace(/\]\([^()\n]*\)/g, "").replace(/[*_~`\\]/g, "");
  const joined = unmarked.replace(TAG, "").replace(ENTITY, "").replace(/[<>|:()[\]]/g, " ");
  const apart = unmarked.replace(TAG, " ").replace(ENTITY, " ").replace(/[<>|:()[\]]/g, " ");
  return GENERATED_LINE.test(spaced) || GENERATED_LINE.test(joined) || GENERATED_LINE.test(apart);
};
// A trailer is read plain, with comments and unknown entities deleted ("Co<!-- -->-authored-by"), and with Markdown emphasis and
// HTML tags deleted too ("**Co-authored-by:** Claude", "<b>Co-authored-by:</b> Claude"); a quote, list or heading mark may precede it.
const coAuthorTrailer = (text) => {
  const t = normalise(text);
  const bare = t.replace(COMMENT, "").replace(ENTITY, "");
  return CO_AUTHOR_TRAILER.test(t) || CO_AUTHOR_TRAILER.test(bare) || CO_AUTHOR_TRAILER.test(bare.replace(TAG, "").replace(/[*_~`\\]/g, ""));
};

// What a commit carries that the rule names: a list of short descriptions, empty for a clean commit.
export function commitFindings(commit) {
  const found = [];
  if (coAuthorTrailer(commit.message)) found.push("a Co-authored-by trailer naming an assistant");
  if (generatedLine(commit.message)) found.push('a "Generated with" line naming an assistant');
  if ((commit.identities ?? []).some((identity) => IDENTITY.test(normalise(identity)))) found.push("an author or committer identity naming an assistant");
  return found;
}

export function evaluate(input) {
  const findings = [];
  for (const [where, text] of [["title", input.title], ["body", input.body]]) {
    if (generatedLine(text)) findings.push(`${where}: a "Generated with" line naming an assistant`);
    if (coAuthorTrailer(text)) findings.push(`${where}: a Co-authored-by line naming an assistant (a squash merge copies the body into the commit on master)`);
  }
  for (const commit of input.commits) {
    const found = commitFindings(commit);
    if (found.length > 0) findings.push(`commit ${commit.sha.slice(0, 12)}: ${found.join(" and ")}; a squash merge can copy it into the commit on master as a Co-authored-by line`);
  }
  return { findings };
}

function parseInput(text) {
  let input;
  try {
    input = JSON.parse(text);
  } catch {
    return null;
  }
  const isString = (value) => typeof value === "string";
  const isStrings = (value) => value === undefined || (Array.isArray(value) && value.every(isString));
  if (input === null || typeof input !== "object" || !isString(input.title) || !isString(input.body) || !Array.isArray(input.commits)) return null;
  if (!input.commits.every((c) => c !== null && typeof c === "object" && isString(c.sha) && isString(c.message) && isStrings(c.identities))) return null;
  return input;
}

if (process.argv[1] && existsSync(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  const input = parseInput(Buffer.concat(chunks).toString("utf8"));
  if (input === null) {
    console.error("check-ai-attribution: the input is not the expected JSON object");
    process.exit(2);
  }
  for (const line of evaluate(input).findings) console.log(`NOTE ${line}`);
  // The last line says the check ran to the end; the gate trusts no answer without it.
  console.log(`CHECKED ${input.commits.length}`);
  process.exit(0);
}
