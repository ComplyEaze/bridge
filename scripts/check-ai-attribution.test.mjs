// Known-answer tests for scripts/check-ai-attribution.mjs, the merge gate's refusal of AI attribution (owner rule of 25 Oct 2026).
// Each case is text a pull request really carried, in both forms the line takes, so the check cannot pass by matching only one.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import test from "node:test";
import { commitFindings, evaluate } from "./check-ai-attribution.mjs";

const SCRIPT = new URL("./check-ai-attribution.mjs", import.meta.url);
const AGENT = "noreply" + "@" + "anthropic.com";
const PLAIN_LINE = "\u{1F916} Generated with Claude Code";
const LINK_LINE = "\u{1F916} Generated with [Claude Code](https://claude.com/claude-code)";
const SHA = "a".repeat(40);
const commit = (message, sha = SHA, identities = undefined) => ({ sha, message, ...(identities ? { identities } : {}) });
const input = (overrides = {}) => ({ title: "Fix a thing (Part of #1)", body: "## Outcome\n\nA fix.\n", commits: [commit("A fix")], ...overrides });
const trailer = `Fix\n\nCo-Authored-By: Claude <${AGENT}>\n`;

test("a clean pull request is clean", () => {
  assert.deepEqual(evaluate(input()), { refusals: [], notes: [] });
});

test("the Generated-with line is refused in the body in both forms, and in the title", () => {
  for (const line of [PLAIN_LINE, LINK_LINE, "Generated with Claude Code", "generated with [claude code](x)", "Generated by Claude", "Generated   with\tClaude Code"]) {
    const result = evaluate(input({ body: `## Outcome\n\nA fix.\n\n${line}\n` }));
    assert.equal(result.refusals.length, 1, JSON.stringify(line));
    assert.match(result.refusals[0], /^body: /);
  }
  assert.equal(evaluate(input({ title: `A fix ${PLAIN_LINE}` })).refusals[0].slice(0, 6), "title:");
});

test("a line hidden in an HTML comment of the body is still refused", () => {
  assert.equal(evaluate(input({ body: `A fix.\n<!-- ${LINK_LINE} -->\n` })).refusals.length, 1);
});

test("text that only mentions the tool, or generated text of another kind, is not refused", () => {
  for (const body of ["Responses generated with OpenAI models.", "Reports generated by Copilot Studio.", "Notes on reviewing with Claude Code.", "Generated with the fixture generator.", "Generated by build.rs", "claude codes", "Code generated with care."]) {
    assert.deepEqual(evaluate(input({ body })), { refusals: [], notes: [] }, body);
  }
});

test("ordinary Markdown, HTML, entities, invisible characters and look-alike letters do not hide the line", () => {
  const hidden = [
    "Generated with **Claude Code**", "Generated with [**Claude Code**](https://claude.com/claude-code)", "Generated with `Claude Code`",
    "Generated with _Claude_ Code", '<a href="x">Generated with Claude Code</a>', "Generated with: Claude Code", "Generated using Claude Code",
    "Generated with \u{1F916} Claude Code", "Generated&nbsp;with&nbsp;Claude Code", "Generated with &#67;laude Code", "Generated with &#x43;laude", "Generated with ClaudeCode",
    "Generated with Cl​aude Code", "Generated w­ith Claude Code", "Generated with Сlaude Code", "Generated with Claude Code",
    "GENERATED WITH CLAUDE CODE", "Generated with a Claude agent",
  ];
  for (const line of hidden) assert.equal(evaluate(input({ body: `A fix.\n${line}\n` })).refusals.length, 1, JSON.stringify(line));
  for (const line of ["Cl​aude <x@example.invalid>", "Claude", "Сlaude"]) {
    for (const prefix of ["Co-authored-by: ", " Co-authored-by: ", "Co‑authored‑by: "]) {
      assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${prefix}${line}\n`)] })).refusals.length, 1, JSON.stringify(prefix + line));
    }
  }
});

test("markup inside the phrase, invisible marks and more look-alikes do not hide the line", () => {
  const hidden = [
    "Generated with <b>Claude</b> Code", '<a href="https://claude.com/claude-code">Generated with Claude Code</a>', 'Generated with <a href="x">Claude Code</a>',
    "Generated with <span>Cl</span>aude", "Gen<!-- x -->erated with Claude", "**Gen**erated with Claude", "Generated with Cl*au*de", "Generated with Cl<b></b>aude",
    "Generated with [**Claude**](https://example.invalid) Code", "Generated with Cl\u034faude Code", "Generated with Cl\ufe0faude Code", "Generated with Cl\u0301aude",
    "Generated with \u03b1", // not the assistant: a lone letter must not match (checked below)
  ].filter((line) => !line.includes("\u03b1"));
  for (const line of hidden) assert.equal(evaluate(input({ body: `A fix.\n${line}\n` })).refusals.length, 1, JSON.stringify(line));
  for (const name of ["Cl\u03b1ude", "\u1d04laude", "\u03f2laude", "Claude\u034f", "ClaudeBot", "claude[bot]", "GitHubCopilot", "OpenAICodex"]) {
    assert.equal(evaluate(input({ commits: [commit(`Fix\n\nCo-authored-by: ${name} <x@example.invalid>\n`)] })).refusals.length, 1, name);
  }
});

test("named entities, tags with no space around them, quoted attributes and comments cannot split or hide the line", () => {
  const hidden = [
    "Gen&shy;erated with Claude Code", "Gen&ZeroWidthSpace;erated with Claude Code", "Gen&zwnj;erated with Claude Code", "Generated&Tab;with Claude Code", "Generated with Cl&zwj;aude",
    "Generated with&NewLine;Claude Code", "Generated with &NoBreak;Claude Code", "Generated with<br>Claude Code", "Generated with<br/>Claude Code",
    "<p>Generated with</p><p>Claude Code</p>", "<td>Generated with</td><td>Claude Code</td>", '<b title="a>b">Gen</b>erated with Claude Code',
    'Gen<b title="a>b">er</b>ated with Claude Code', "Gen<!-- x -->erated with Claude", "Generated with Cl\u3164aude", "Generated with Cl\u115faude",
  ];
  for (const line of hidden) assert.equal(evaluate(input({ body: `A fix.\n${line}\n` })).refusals.length, 1, JSON.stringify(line));
  for (const trailer of ["Co<!-- -->-authored-by: Claude", "Co-authored-by: Cl&zwj;aude", "Co-authored-by: Opus", "Co-authored-by: Sonnet <x@example.invalid>", "Co-authored-by: Haiku"]) {
    assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${trailer}\n`)] })).refusals.length, 1, trailer);
  }
});

test("names that only sit inside a longer word are not assistants", () => {
  for (const line of ["Co-authored-by: Affable Person <x@example.invalid>", "Co-authored-by: A Philanthropic Fund", "Co-authored-by: Carlos Codexo", "Co-authored-by: Opusculum Press", "Co-authored-by: Haikuist"]) {
    assert.deepEqual(evaluate(input({ commits: [commit(`Fix\n\n${line}\n`)] })), { refusals: [], notes: [] }, line);
  }
  assert.deepEqual(evaluate(input({ commits: [commit("Fix", SHA, ["affable", "philanthropic@example.invalid", "Opusculum Press"])] })), { refusals: [], notes: [] });
});

test("pathological markup does not make the match slow", () => {
  const started = Date.now();
  evaluate(input({ body: "<a".repeat(40_000) + "\n" + "](".repeat(40_000) + "\n" + '<a "'.repeat(20_000), commits: [commit("<a".repeat(40_000))] }));
  assert.ok(Date.now() - started < 2000, `took ${Date.now() - started} ms`);
});

test("a Co-authored-by trailer naming an assistant is refused on a commit that is not accepted, whatever its date", () => {
  for (const name of [`Claude <${AGENT}>`, `claude <${AGENT}>`, "Claude", `Someone <${AGENT}>`, "Anthropic Bot <bot@example.invalid>", "Fable <x@example.invalid>", "Copilot <x@example.invalid>", "Codex", "ChatGPT", "OpenAI Bot <x@example.invalid>"]) {
    for (const eol of ["\n", "\r\n"]) {
      const result = evaluate(input({ commits: [commit(`A fix${eol}${eol}Co-Authored-By: ${name}${eol}`, "b".repeat(40))] }));
      assert.equal(result.refusals.length, 1, JSON.stringify(name + eol));
      assert.match(result.refusals[0], /^commit bbbbbbbbbbbb: a Co-authored-by trailer naming an assistant, and it is not one of the accepted older commits/);
    }
  }
});

test("an accepted older commit with the same text is reported, not refused, and the note says a squash can copy it", () => {
  const result = evaluate(input({ commits: [commit(trailer, SHA)], accepted: [SHA] }));
  assert.deepEqual(result.refusals, []);
  assert.equal(result.notes.length, 1);
  assert.match(result.notes[0], /accepted older commit, but a squash merge can copy it into the commit on master as a Co-authored-by line/);
  assert.equal(evaluate(input({ commits: [commit(trailer, SHA)], accepted: [SHA.toUpperCase()] })).refusals.length, 0, "a SHA is compared without regard to case");
  assert.equal(evaluate(input({ commits: [commit(trailer, SHA)], accepted: ["b".repeat(40)] })).refusals.length, 1, "another SHA on the list does not help");
});

test("acceptance is the whole SHA: a list entry that shares only a prefix with the commit does not accept it", () => {
  const sha = "1234567890abcdef1234567890abcdef12345678";
  for (const near of [sha.slice(0, 7), sha.slice(0, 12), sha.slice(0, 39) + "9", sha.slice(0, 39)]) {
    assert.equal(evaluate(input({ commits: [commit(trailer, sha)], accepted: [near] })).refusals.length, 1, near);
  }
  assert.equal(evaluate(input({ commits: [commit(trailer, sha)], accepted: [sha] })).refusals.length, 0);
});

test("a commit is accepted by its SHA and by nothing else: no date, message or position can stand in", () => {
  const accepted = [SHA];
  const other = commit(trailer, "c".repeat(40));
  assert.equal(evaluate(input({ commits: [commit(trailer, SHA), other], accepted })).refusals.length, 1);
  assert.equal(evaluate(input({ commits: [other, commit(trailer, SHA)], accepted })).refusals.length, 1);
  assert.equal(evaluate(input({ commits: [{ ...other, committed_at: "2020-01-01T00:00:00Z", parents: [SHA] }], accepted })).refusals.length, 1, "a date or a parent on the list is not acceptance");
});

test("a commit whose identity names an assistant counts like a trailer, and a squash would copy it just the same", () => {
  const byIdentity = evaluate(input({ commits: [commit("A fix", SHA, ["Claude", `noreply@${"anthropic.com"}`])] }));
  assert.equal(byIdentity.refusals.length, 1);
  assert.match(byIdentity.refusals[0], /an author or committer identity naming an assistant, and it is not one of the accepted older commits/);
  assert.equal(evaluate(input({ commits: [commit("A fix", SHA, ["Claude"])], accepted: [SHA] })).notes.length, 1);
  assert.deepEqual(evaluate(input({ commits: [commit("A fix", SHA, ["A Person", "person@example.invalid", "GitHub", "noreply@github.com"])] })), { refusals: [], notes: [] });
});

test("the body and title may not carry a Co-authored-by line naming an assistant either, since a squash merge copies the body into master", () => {
  for (const line of [`Co-Authored-By: Claude <${AGENT}>`, "co-authored-by: Claude", "Co-authored-by: Anthropic"]) {
    const result = evaluate(input({ body: `A fix.\n\n${line}\n` }));
    assert.equal(result.refusals.length, 1, line);
    assert.match(result.refusals[0], /^body: a Co-authored-by line/);
  }
  assert.match(evaluate(input({ title: "Fix\nCo-authored-by: Claude" })).refusals[0], /^title: a Co-authored-by line/);
});

test("a person whose name begins with the assistant's name is not an assistant, and the tool's own spellings are", () => {
  assert.deepEqual(evaluate(input({ commits: [commit("Fix\n\nCo-authored-by: Claudette Smith <claudette@example.invalid>\n")], body: "Thanks to Claudette. Generated with Claudette's help.\n" })), { refusals: [], notes: [] });
  assert.equal(evaluate(input({ commits: [commit("Fix\n\nCo-authored-by: claude-code <x@example.invalid>\n")] })).refusals.length, 1);
  assert.equal(evaluate(input({ body: "Generated with ClaudeCode\n" })).refusals.length, 1);
});

test("a human co-author, and a message that only mentions the assistant in a later line, are not refused", () => {
  assert.deepEqual(evaluate(input({ commits: [commit("Fix\n\nCo-authored-by: A Person <person@example.invalid>\n")] })), { refusals: [], notes: [] });
  assert.deepEqual(evaluate(input({ commits: [commit("Fix\n\nThanks to Claude for the idea. Co-authored-by is a trailer name.\n")] })), { refusals: [], notes: [] });
});

test("a Generated-with line in a commit message is a finding of the same kind", () => {
  assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${PLAIN_LINE}\n`)] })).refusals.length, 1);
  assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${LINK_LINE}\n`)], accepted: [SHA] })).notes.length, 1);
  assert.deepEqual(commitFindings(commit("Fix")), []);
});

test("several findings are all reported, each with where it is", () => {
  const result = evaluate(input({
    body: `A fix.\n${LINK_LINE}\n`,
    commits: [commit(trailer, "c".repeat(40)), commit(trailer, "d".repeat(40))],
    accepted: ["d".repeat(40)],
  }));
  assert.equal(result.refusals.length, 2);
  assert.equal(result.notes.length, 1);
});

test("a very long run of spaces does not hang the match", () => {
  const started = Date.now();
  evaluate(input({ body: `Generated with${" ".repeat(200_000)}x`, commits: [commit(`Fix\n\nCo-authored-by:${" ".repeat(200_000)}x`)] }));
  assert.ok(Date.now() - started < 1500, `took ${Date.now() - started} ms`);
});

test("the accepted list is well formed: 40 lowercase hex, unique, each with a pull request number", () => {
  const list = JSON.parse(readFileSync(new URL("./check-ai-attribution-accepted.json", import.meta.url), "utf8"));
  assert.equal(typeof list.note, "string");
  assert.ok(list.accepted.length > 0);
  for (const entry of list.accepted) {
    assert.match(entry.sha, /^[0-9a-f]{40}$/);
    assert.ok(Number.isInteger(entry.pull) && entry.pull > 0);
  }
  assert.equal(new Set(list.accepted.map((entry) => entry.sha)).size, list.accepted.length);
});

function run(stdin) {
  const result = spawnSync(process.execPath, [SCRIPT.pathname], { input: stdin, encoding: "utf8" });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

test("the command line: exit 0 clean, 1 refused with the findings, 2 on input that is not the expected shape", () => {
  assert.deepEqual(run(JSON.stringify(input())), { status: 0, stdout: "CHECKED 1\n", stderr: "" });
  const refused = run(JSON.stringify(input({ body: LINK_LINE })));
  assert.equal(refused.status, 1);
  assert.match(refused.stdout, /^REFUSE body: .*\nCHECKED 1\n$/);
  const noted = run(JSON.stringify(input({ commits: [commit(trailer)], accepted: [SHA] })));
  assert.equal(noted.status, 0);
  assert.match(noted.stdout, /^NOTE commit .*\nCHECKED 1\n$/);
  for (const bad of ["", "not json", "[]", "{}", JSON.stringify({ title: "t", body: "b" }), JSON.stringify({ title: "t", body: "b", commits: [{ sha: "x" }] }), JSON.stringify({ title: 1, body: "b", commits: [] }), JSON.stringify({ title: "t", body: "b", commits: [], accepted: "x" })]) {
    assert.equal(run(bad).status, 2, bad);
  }
});
