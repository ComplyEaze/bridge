// Known-answer tests for scripts/check-ai-attribution.mjs, the merge gate's refusal of AI attribution (owner rule of 25 Oct 2026).
// Each case is text a pull request really carried, in both forms the line takes, so the check cannot pass by matching only one.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import test from "node:test";
import { evaluate, RULE_FROM } from "./check-ai-attribution.mjs";

const SCRIPT = new URL("./check-ai-attribution.mjs", import.meta.url);
const AGENT = "noreply" + "@" + "anthropic.com";
const PLAIN_LINE = "\u{1F916} Generated with Claude Code";
const LINK_LINE = "\u{1F916} Generated with [Claude Code](https://claude.com/claude-code)";
const BEFORE = "2026-10-25T12:59:59Z";
const AFTER = "2026-10-25T13:00:00Z";
const commit = (message, committed_at = AFTER, sha = "a".repeat(40)) => ({ sha, message, committed_at });
const input = (overrides = {}) => ({ title: "Fix a thing (Part of #1)", body: "## Outcome\n\nA fix.\n", commits: [commit("A fix")], ...overrides });

test("a clean pull request is clean", () => {
  assert.deepEqual(evaluate(input()), { refusals: [], notes: [] });
});

test("the Generated-with line is refused in the body in both forms, and in the title", () => {
  for (const line of [PLAIN_LINE, LINK_LINE, "Generated with Claude Code", "generated with [claude code](x)", "Generated by Claude", "Generated   with\tClaude Code"]) {
    const result = evaluate(input({ body: `## Outcome\n\nA fix.\n\n${line}\n` }));
    assert.equal(result.refusals.length, 1, JSON.stringify(line));
    assert.match(result.refusals[0], /^body: /);
  }
  assert.equal(evaluate(input({ title: `A fix ${PLAIN_LINE}` })).refusals[0].slice(0, 6), "title:");
});

test("a line hidden in an HTML comment of the body is still refused", () => {
  assert.equal(evaluate(input({ body: `A fix.\n<!-- ${LINK_LINE} -->\n` })).refusals.length, 1);
});

test("text that only mentions Claude Code, or generated text of another kind, is not refused", () => {
  for (const body of ["The lane runs in Claude Code.", "Generated with the fixture generator.", "Generated by build.rs", "claude codes", "Code generated with care."]) {
    assert.deepEqual(evaluate(input({ body })), { refusals: [], notes: [] }, body);
  }
});

test("a Co-authored-by trailer naming Claude or Anthropic, made at or after the rule, is refused", () => {
  for (const trailer of [`Co-Authored-By: Claude Sonnet 5.5 <${AGENT}>`, `Co-authored-by: Claude <${AGENT}>`, "co-authored-by: Claude Opus 5.5", `CO-AUTHORED-BY: Someone <${AGENT}>`, "Co-Authored-By: Anthropic Bot <bot@example.invalid>"]) {
    for (const eol of ["\n", "\r\n"]) {
      const message = `A fix${eol}${eol}${trailer}${eol}`;
      const result = evaluate(input({ commits: [commit(message, AFTER, "b".repeat(40))] }));
      assert.equal(result.refusals.length, 1, JSON.stringify(trailer + eol));
      assert.match(result.refusals[0], /^commit bbbbbbbbbbbb: a Co-authored-by trailer naming Claude or Anthropic, made after the rule/);
    }
  }
});

test("the same trailer on a commit made before the rule is reported, not refused", () => {
  const result = evaluate(input({ commits: [commit(`Old\n\nCo-Authored-By: Claude <${AGENT}>\n`, BEFORE)] }));
  assert.deepEqual(result.refusals, []);
  assert.equal(result.notes.length, 1);
  assert.match(result.notes[0], /made before the rule/);
});

test("the cutoff is the instant given: one second before passes, the instant itself is refused", () => {
  const message = `Fix\n\nCo-Authored-By: Claude <${AGENT}>\n`;
  assert.equal(evaluate(input({ commits: [commit(message, "2026-10-25T12:59:59Z")] })).refusals.length, 0);
  assert.equal(evaluate(input({ commits: [commit(message, "2026-10-25T13:00:00Z")] })).refusals.length, 1);
  assert.equal(evaluate(input({ commits: [commit(message, "2026-10-25T18:30:00+05:30")] })).refusals.length, 1, "an offset date is read as an instant (13:00Z)");
  assert.equal(evaluate(input({ commits: [commit(message, "2026-10-25T18:29:59+05:30")] })).refusals.length, 0);
  assert.equal(RULE_FROM, "2026-10-25T13:00:00Z");
});

test("a commit with such a trailer and an unreadable date is refused, and one without a trailer is not looked at", () => {
  const message = `Fix\n\nCo-Authored-By: Claude <${AGENT}>\n`;
  for (const date of ["", "yesterday", "not a date"]) {
    const result = evaluate(input({ commits: [commit(message, date)] }));
    assert.equal(result.refusals.length, 1, date);
    assert.match(result.refusals[0], /its date cannot be read/);
  }
  assert.deepEqual(evaluate(input({ commits: [commit("A plain commit", "garbage")] })), { refusals: [], notes: [] });
});

test("a human co-author, and a trailer that only mentions Claude in a later line, are not refused", () => {
  assert.deepEqual(evaluate(input({ commits: [commit("Fix\n\nCo-authored-by: A Person <person@example.invalid>\n")] })), { refusals: [], notes: [] });
  assert.deepEqual(evaluate(input({ commits: [commit("Fix\n\nThanks to Claude for the idea. Co-authored-by is a trailer name.\n")] })), { refusals: [], notes: [] });
});

test("a Generated-with line in a commit message follows the same dates", () => {
  assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${PLAIN_LINE}\n`, AFTER)] })).refusals.length, 1);
  assert.equal(evaluate(input({ commits: [commit(`Fix\n\n${LINK_LINE}\n`, BEFORE)] })).notes.length, 1);
});

test("several findings are all reported, each with where it is", () => {
  const result = evaluate(input({
    body: `A fix.\n${LINK_LINE}\n`,
    commits: [commit(`Fix\n\nCo-Authored-By: Claude <${AGENT}>\n`, AFTER, "c".repeat(40)), commit(`Old\n\nCo-Authored-By: Claude <${AGENT}>\n`, BEFORE, "d".repeat(40))],
  }));
  assert.equal(result.refusals.length, 2);
  assert.equal(result.notes.length, 1);
});

function run(stdin) {
  const result = spawnSync(process.execPath, [SCRIPT.pathname], { input: stdin, encoding: "utf8" });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

test("the command line: exit 0 clean, 1 refused with the findings, 2 on input that is not the expected shape", () => {
  assert.deepEqual(run(JSON.stringify(input())), { status: 0, stdout: "", stderr: "" });
  const refused = run(JSON.stringify(input({ body: LINK_LINE })));
  assert.equal(refused.status, 1);
  assert.match(refused.stdout, /^REFUSE body: /);
  const noted = run(JSON.stringify(input({ commits: [commit(`Old\n\nCo-Authored-By: Claude <${AGENT}>\n`, BEFORE)] })));
  assert.equal(noted.status, 0);
  assert.match(noted.stdout, /^NOTE commit /);
  for (const bad of ["", "not json", "[]", "{}", JSON.stringify({ title: "t", body: "b" }), JSON.stringify({ title: "t", body: "b", commits: [{ sha: "x" }] }), JSON.stringify({ title: 1, body: "b", commits: [] })]) {
    assert.equal(run(bad).status, 2, bad);
  }
});
